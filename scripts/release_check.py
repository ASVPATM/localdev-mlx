#!/usr/bin/env python3
"""Validate source and the exact wheel in isolated environments; never tag/publish."""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile
import zipfile
from pathlib import Path


def run(args, *, cwd, env):
    print("+ " + " ".join(map(str, args)), flush=True)
    subprocess.run(list(map(str, args)), cwd=cwd, env=env, check=True)


def install_wheel(wheel, python, constraints, *, cwd, env, flow_browser):
    # Test the artifact against the same dependency versions as the source.
    # In particular, Playwright must match the explicitly downloaded Chromium.
    run(
        [
            "uv",
            "export",
            "--locked",
            "--group",
            "dev",
            "--no-emit-project",
            "--no-hashes",
            *(["--extra", "flow-browser"] if flow_browser else []),
            "--output-file",
            constraints,
        ],
        cwd=cwd,
        env=env,
    )
    run(
        [
            "uv",
            "pip",
            "install",
            "--python",
            python,
            "--constraint",
            constraints,
            str(wheel) + ("[flow-browser]" if flow_browser else ""),
            "pytest>=8,<10",
        ],
        cwd=cwd,
        env=env,
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--allow-dirty",
        action="store_true",
        help="Development check only; release requires clean tracked files.",
    )
    parser.add_argument(
        "--artifacts", type=Path, help="Copy the verified wheel and sdist to this directory."
    )
    parser.add_argument(
        "--flow-browser",
        action="store_true",
        help="Include recording Chromium tests (browser must already be explicitly installed).",
    )
    args = parser.parse_args()
    test_options = ["-o", "addopts=", "-o", "faulthandler_timeout=15", "-q", "-ra"]
    root = Path(__file__).resolve().parent.parent
    env = os.environ.copy()
    env.pop("PYTHONPATH", None)
    env.pop("VIRTUAL_ENV", None)
    if not args.allow_dirty:
        dirty = subprocess.check_output(
            ["git", "status", "--porcelain", "--untracked-files=no"], cwd=root, text=True
        )
        if dirty.strip():
            raise SystemExit("Commit tracked changes before release validation")
    with tempfile.TemporaryDirectory(prefix="localdev-release-") as temporary:
        temp = Path(temporary)
        artifact_dir = args.artifacts.resolve() if args.artifacts else None
        if not args.allow_dirty:
            checkout = temp / "checkout"
            checkout.mkdir()
            archive = subprocess.check_output(["git", "archive", "HEAD"], cwd=root)
            subprocess.run(["tar", "-x", "-C", str(checkout)], input=archive, check=True)
            root = checkout
        env["LOCALDEV_MLX_HOME"] = str(temp / "runtime")
        run(
            [
                "uv",
                "sync",
                "--locked",
                "--group",
                "dev",
                *(["--extra", "flow-browser"] if args.flow_browser else []),
            ],
            cwd=root,
            env=env,
        )
        for command in (
            ["uv", "run", "--no-sync", "ruff", "check", "."],
            ["uv", "run", "--no-sync", "pytest", *test_options],
            ["uv", "run", "--no-sync", "python", "-m", "compileall", "-q", "src", "tests"],
            ["uv", "build", "--out-dir", temp / "dist"],
        ):
            run(command, cwd=root, env=env)
        wheel = next((temp / "dist").glob("*.whl"))
        for artifact in (temp / "dist").iterdir():
            if artifact.suffix == ".whl":
                with zipfile.ZipFile(artifact) as archive:
                    names = archive.namelist()
                    for name in (
                        "dashboard.html",
                        "app.js",
                        "inspector.js",
                        "style.css",
                        "LICENSE",
                        "examples/web/project-flow.toml",
                        "examples/web/src/server.py",
                        "examples/manual/project-flow.toml",
                    ):
                        assert "localdev_mlx/flow/" + name in names, name
            elif artifact.name.endswith(".tar.gz"):
                with tarfile.open(artifact) as archive:
                    names = archive.getnames()
            else:
                continue
            assert not any(Path(name).name == "STABILIZATION_HANDOFF.md" for name in names), (
                f"Private stabilization handoff leaked into {artifact.name}"
            )
            assert not any(
                "__pycache__" in name or name.endswith((".pyc", ".pyo")) for name in names
            ), "Generated bytecode leaked into a package"
            assert not any(
                "/output/" in name or "LOCALDEV_MLX_FLOW_IMPLEMENTATION_HANDOFF.md" in name
                for name in names
            ), "Private working inputs leaked into a package"
        print(
            "Privacy check passed: stabilization handoff excluded from wheel and sdist", flush=True
        )
        run(["uv", "venv", "--python", sys.executable, temp / "wheel-env"], cwd=root, env=env)
        python = temp / "wheel-env/bin/python"
        cli = temp / "wheel-env/bin/localdev-mlx"
        env["PATH"] = str(cli.parent) + os.pathsep + env.get("PATH", "")
        install_wheel(
            wheel,
            python,
            temp / "wheel-constraints.txt",
            cwd=root,
            env=env,
            flow_browser=args.flow_browser,
        )
        identity = subprocess.check_output(
            [
                python,
                "-I",
                "-c",
                "import json; from localdev_mlx.diagnostics import installation_identity; print(json.dumps(installation_identity()))",
            ],
            cwd=temp,
            env=env,
            text=True,
        )
        values = json.loads(identity)
        assert values["versions_agree"], values
        assert str(temp / "wheel-env") in values["module_path"], values
        print(identity, flush=True)
        for command in (
            ["--version"],
            ["--help"],
            ["configure", "--check"],
            ["session", "--help"],
            ["plan", "--help"],
            ["flow", "--help"],
            ["flow", "doctor", "--project", str(temp)],
        ):
            run([cli, *command], cwd=temp, env=env)
        run(
            [python, "-I", "-m", "pytest", *test_options, root / "tests"],
            cwd=temp,
            env=env,
        )
        if artifact_dir:
            artifact_dir.mkdir(parents=True, exist_ok=True)
            for artifact in (temp / "dist").iterdir():
                if artifact.is_file():
                    shutil.copy2(artifact, artifact_dir / artifact.name)
        print(
            "Release checks passed: source, wheel, CLI, session and mock workflows. Real MLX checks are separate.",
            flush=True,
        )


if __name__ == "__main__":
    main()
